export function getListingById(id: number): Listing | undefined {
  return listings.find((item) => item.id === id);
}

export function getRelatedListings(current: Listing, limit = 6): Listing[] {
  return listings
    .filter((item) => item.id !== current.id && item.district === current.district)
    .slice(0, limit);
}
