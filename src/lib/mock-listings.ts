const BUILDING_ILLUSTRATION_COUNT = 6;

// 실제 매물 사진이 없는 샘플 데이터이므로, 무작위 스톡 사진(엉뚱한 풍경 등) 대신
// 사무실/빌딩 테마의 자체 제작 일러스트를 시드값 기준으로 결정적으로 배정한다.
function PLACEHOLDER_IMG(seed: string) {
  const hash = [...seed].reduce((sum, ch) => sum + ch.charCodeAt(0), 0);
  const index = (hash % BUILDING_ILLUSTRATION_COUNT) + 1;
  return `/images/building-0${index}.svg`;
}

